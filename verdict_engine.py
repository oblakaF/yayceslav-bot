_RECENT: deque[str] = deque(maxlen=VERDICT_RECENT_MAXLEN)


def reset_recent() -> None:
    _RECENT.clear()


def choose_verdict(
    conversation_mode: str,
    *,
    taunt_already_selected: bool = False,
    rng=random,
) -> str | None:
    """Возвращает редкий хвост только для conflict/banter режимов."""

    if conversation_mode not in {"hostile", "challenge"}:
        return None

    # Не делаем двойной дожим: либо taunt, либо хвост-вердикт.
    if taunt_already_selected:
        return None

    if rng.random() >= VERDICT_CHANCE:
        return None

    candidates = [item for item in VERDICTS if item not in _RECENT]
    if not candidates:
        _RECENT.clear()
        candidates = list(VERDICTS)

    chosen = rng.choice(candidates)
    _RECENT.append(chosen)
    return chosen
