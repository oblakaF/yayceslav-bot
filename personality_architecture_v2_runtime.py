def _find_bot_module() -> Any | None:
    for name in ("__main__", "bot"):
        module = sys.modules.get(name)
        if module is not None and callable(getattr(module, "build_full_system_instruction", None)):
            return module
    return None


def install(bot_module: Any | None = None) -> bool:
    """Append the architecture contract to the final system instruction."""
    global _INSTALLED

    module = bot_module or _find_bot_module()
    if module is None:
        return False
    if _INSTALLED:
        return True

    original = getattr(module, "build_full_system_instruction", None)
    if not callable(original):
        return False
    if getattr(original, "_yayceslav_personality_architecture_v2", False):
        _INSTALLED = True
        return True

    @functools.wraps(original)
    def build_with_personality_architecture(*args: Any, **kwargs: Any) -> str:
        instruction = str(original(*args, **kwargs))
        return instruction.rstrip() + "\n\n" + ARCHITECTURE_RULE

    build_with_personality_architecture._yayceslav_personality_architecture_v2 = True
    module.build_full_system_instruction = build_with_personality_architecture
    _INSTALLED = True
    logging.warning(
        "Personality architecture v2 ready: task > temperament > self-canon > scene > style"
    )
    return True
