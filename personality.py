def is_serious_text(
    text: str,
) -> bool:
    """Определяет чувствительную или опасную тему."""

    return bool(
        SERIOUS_RE.search(text)
    )


def detect_conversation_mode(
    text: str,
) -> str:
    """Определяет нужный стиль ответа."""

    lowered = text.lower().strip()

    if is_serious_text(lowered):
        return "serious"

    if HOSTILE_RE.search(lowered):
        return "hostile"

    if CHALLENGE_RE.search(lowered):
        return "challenge"

    if GREETING_RE.search(lowered):
        return "greeting"

    return "normal"


def maybe_pick(
    youth: list[str],
    skoof: list[str],
    chance: float,
    max_count: int = 1,
    youth_bias: float = 0.50,
) -> list[str]:
    """
    Иногда выбирает варианты из словарей.

    В большинстве обычных ответов возвращает пустой список.
    """

    if random.random() >= chance:
        return []

    if random.random() < youth_bias:
        pool = youth
    else:
        pool = skoof

    if max_count <= 1:
        count = 1
    else:
        count = random.randint(
            1,
            max_count,
        )

    return random.sample(
        pool,
        k=min(
            count,
            len(pool),
        ),
    )

