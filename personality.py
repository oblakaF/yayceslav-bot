def is_serious_text(
    text: str,
) -> bool:
    """Определяет чувствительную или опасную тему."""

    return bool(
        SERIOUS_RE.search(text)
    )


def detect_conversation_mode(
    text: str,
) -> str:
    """Определяет нужный стиль ответа."""

    lowered = text.lower().strip()

    if is_serious_text(lowered):
        return "serious"

    if HOSTILE_RE.search(lowered):
        return "hostile"

    if CHALLENGE_RE.search(lowered):
        return "challenge"

    if GREETING_RE.search(lowered):
        return "greeting"

    return "normal"


